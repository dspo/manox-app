fn user_message() -> ahp_types::state::Message {
    serde_json::from_value(serde_json::json!({
        "text": "pick the editor",
        "origin": { "kind": "user" },
    }))
    .expect("a user message parses")
}

#[gpui::test]
async fn the_ask_wire_parses_and_folds_into_the_interactive_card(cx: &mut TestAppContext) {
    init_harness(cx);
    let (_window, workspace) = open_workspace(cx);
    let mut visual = VisualTestContext::from_window(_window.into(), cx);

    // ── Wire face: the frozen literal still deserializes through the union,
    // every kind in its own arm, every field at its expected value.
    let value: serde_json::Value =
        serde_json::from_str(WIRE_ASK).expect("the frozen literal is valid JSON");
    let action =
        serde_json::from_value::<StateAction>(value).expect("the ask wire's shape is unchanged");
    let StateAction::ChatInputRequested(ref requested) = action else {
        panic!("the literal must deserialize as chat/inputRequested");
    };
    let request = &requested.request;
    assert_eq!(request.id, "wire-ask-1", "the request id routes the answer");
    assert_eq!(
        request.url.as_deref(),
        Some("https://example.com/review"),
        "the request-level url survives the wire"
    );
    let answers = request
        .answers
        .as_ref()
        .expect("the draft answers ride along");
    assert_eq!(answers.len(), 2, "both answer arms deserialize");
    let ChatInputAnswer::Draft(answered) = answers
        .get("q-editor")
        .expect("the draft answer's key matches its question id")
    else {
        panic!("q-editor carries a draft answer");
    };
    let ChatInputAnswerValue::Selected(ChatInputSelectedAnswerValue { value, .. }) =
        &answered.value
    else {
        panic!("the draft's value is a selected option");
    };
    assert_eq!(value, "monaco", "the answer-value union's tag and payload");
    let ChatInputAnswer::Skipped(_) = answers.get("q-notes").expect("the skipped answer") else {
        panic!("q-notes carries a skip");
    };

    let questions = request
        .questions
        .as_deref()
        .expect("the request carries its questions");
    assert_eq!(questions.len(), 6, "every question kind of the current pin");

    let ChatInputQuestion::SingleSelect(editor) = &questions[0] else {
        panic!("the first question is single-select");
    };
    assert_eq!(editor.title.as_deref(), Some("编辑器面板"), "the header");
    assert_eq!(
        editor.message, "编辑器面板用什么方案？",
        "the 2026-11-02 incident's original wording"
    );
    assert_eq!(editor.required, Some(true));
    assert_eq!(
        editor.allow_freeform_input,
        Some(true),
        "camelCase scalars survive the wire"
    );
    let recommended: Vec<_> = editor
        .options
        .iter()
        .filter(|o| o.recommended == Some(true))
        .collect();
    assert_eq!(
        recommended.len(),
        1,
        "exactly one option carries the recommendation"
    );
    assert_eq!(
        recommended[0].id, "monaco",
        "the recommendation sits on Monaco"
    );
    assert_eq!(recommended[0].label, "Monaco");
    assert_eq!(
        recommended[0].description.as_deref(),
        Some("内嵌 web 编辑器")
    );
    let labels: Vec<_> = editor.options.iter().map(|o| o.label.as_str()).collect();
    assert_eq!(
        labels,
        ["Monaco", "CodeMirror 6", "原生 TextEdit"],
        "the incident's three options, in order"
    );

    let ChatInputQuestion::MultiSelect(tools) = &questions[1] else {
        panic!("the second question is multi-select");
    };
    assert_eq!(tools.title.as_deref(), Some("启用工具"));
    assert_eq!(tools.required, Some(false));
    assert_eq!(tools.allow_freeform_input, Some(true));
    assert_eq!(tools.min, Some(1));
    assert_eq!(tools.max, Some(2));

    let ChatInputQuestion::Text(notes) = &questions[2] else {
        panic!("the third question is text");
    };
    assert_eq!(notes.title.as_deref(), Some("备注"));
    assert_eq!(notes.required, Some(true));
    assert_eq!(notes.format.as_deref(), Some("uri"));
    assert_eq!(notes.min, Some(1));
    assert_eq!(notes.max, Some(200));
    assert_eq!(
        notes.default_value.as_deref(),
        Some("https://example.com"),
        "camelCase compound names survive the wire"
    );

    let ChatInputQuestion::Number(budget) = &questions[3] else {
        panic!("the fourth question is number");
    };
    assert_eq!(budget.title.as_deref(), Some("预算小时"));
    assert_eq!(budget.required, Some(true));
    assert_eq!(budget.min, Some(0.5));
    assert_eq!(budget.max, Some(10.5));
    assert_eq!(budget.default_value, Some(2.5));

    let ChatInputQuestion::Integer(reviewers) = &questions[4] else {
        panic!("the fifth question is integer (distinct from number's tag)");
    };
    assert_eq!(reviewers.title.as_deref(), Some("评审人数"));
    assert_eq!(reviewers.required, Some(false));
    assert_eq!(reviewers.min, Some(1.0));
    assert_eq!(reviewers.max, Some(8.0));
    assert_eq!(reviewers.default_value, Some(3.0));

    let ChatInputQuestion::Boolean(notify) = &questions[5] else {
        panic!("the sixth question is boolean");
    };
    assert_eq!(notify.title.as_deref(), Some("完成通知"));
    assert_eq!(notify.required, Some(true));
    assert_eq!(notify.default_value, Some(true));

    // ── Fold face: the deserialized action arms the card the production way.
    let store = cx.update(|cx| cx.new(|_| AhpStore::detached()));
    workspace.update(&mut visual.cx, |ws, cx| {
        ws.diagnostic_bind_store(store.clone(), "sess-1", cx);
    });
    store.update(&mut visual.cx, |s, _| {
        // The reducer parks input requests on the active turn, so the turn
        // opens first (the sibling ask tests share this ordering).
        s.book.apply(
            &chat_uri("sess-1"),
            &ahp_types::actions::StateAction::ChatTurnStarted(
                ahp_types::actions::ChatTurnStartedAction {
                    turn_id: "turn-1".to_string(),
                    started_at: "2026-11-02T00:00:00Z".to_string(),
                    message: user_message(),
                    queued_message_id: None,
                    meta: None,
                },
            ),
        );
        s.book.apply(&chat_uri("sess-1"), &action);
    });

    let ask = store.read_with(&visual.cx, |s, _| {
        let view = leaf(&s.book, "sess-1");
        let (_, req) = view
            .open_chat_input()
            .expect("the fold holds the deserialized request");
        assert_eq!(req.id, "wire-ask-1");
        pending_ask_from_ahp(req.id.clone(), req)
            .expect("the folded request parses into the interactive card")
    });
    // The count is the kind-tag tripwire: an unknown kind falls into the
    // union's `Unknown` variant and `pending_ask_from_ahp` skips it, so a
    // respelled tag silently shrinks the card instead of failing the parse.
    assert_eq!(ask.questions.len(), 6, "every question survives the fold");
    assert_eq!(ask.questions[0].header, "编辑器面板");
    assert_eq!(ask.questions[0].question, "编辑器面板用什么方案？");
    assert!(!ask.questions[0].multi_select);
    assert!(
        ask.questions[0]
            .options
            .iter()
            .find(|o| o.label == "Monaco")
            .expect("Monaco survives the fold")
            .recommended
    );
    assert!(
        ask.questions[1].multi_select,
        "the multi-select kind flips the card's selection model"
    );
    for q in &ask.questions[2..] {
        assert!(
            q.options.is_empty() && !q.multi_select,
            "text/number/integer/boolean render as the card's custom-input step"
        );
    }
    assert!(
        ask.questions[0].detail.contains("Editor panel"),
        "the request-level support markdown folds into the first question's detail"
    );
    assert!(
        ask.questions[1..].iter().all(|q| q.detail.is_empty()),
        "the document belongs to the first question only"
    );

    // ── Workspace face: the live edge arms the composer in ask mode and the
    // projection renders exactly one interactive card for the request.
    workspace.update(&mut visual.cx, |ws, cx| {
        ws.diagnostic_sync_conversation(cx);
        ws.diagnostic_sync_live_ask(cx);
        ws.diagnostic_sync_ask_card_snapshots(cx);
    });
    assert_eq!(
        workspace.read_with(&visual.cx, |ws, cx| ws.diagnostic_pending_ask_id(cx)),
        Some("wire-ask-1".to_string()),
        "the composer is armed in ask mode against the wire's request id"
    );
    assert!(
        workspace.read_with(&visual.cx, |ws, cx| ws
            .diagnostic_ask_card_interactive("wire-ask-1", cx)),
        "the ask card snapshot exists and is interactive"
    );
    assert_eq!(
        workspace.read_with(&visual.cx, |ws, cx| ws
            .diagnostic_tool_call_count("wire-ask-1", cx)),
        1,
        "exactly one ask card for the wire's request"
    );
    manox_agent::thread_store::drop_global_for_test();
}
