//! The ask wire's serde shape, pinned against a frozen literal. The sibling
//! ask tests build `ChatInputRequest` structs, which a field addition or
//! removal catches at compile time — but a serde drift (a field rename, a
//! `kind` tag respelled, camelCase flipping to snake_case, the action union's
//! `type` tag changing shape) compiles fine and only breaks the user's card
//! on an `ahp-types` bump. Deserializing a frozen wire literal through
//! `StateAction` is the only check that sees that layer. Calibration: the
//! literal carries every question kind and every field of the current pin's
//! shape, and the assertions read each of them — so any rename, tag
//! respelling, or type change goes red (an unknown `kind` falls into the
//! union's `Unknown` variant and silently vanishes from the card, which the
//! fold-count assertion catches). What stays green: serde ignores unknown
//! fields, so a future field the fold does not need yet is a legal addition —
//! nothing here is an exhaustive-equality pin.
#![cfg(feature = "test-support")]

